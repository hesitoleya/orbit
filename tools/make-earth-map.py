def draw_polys(draw, polys, W, H, fill):
    for poly in polys:
        draw.polygon([xy(lon, lat, W, H) for lon, lat in poly], fill=fill)

def fbm_field(w, h, octaves, base_grid, seed, aspect=2.0):
    """多倍频 value noise（用 PIL 的双三次放大当插值器），返回 -1..1 的 float32 场"""
    rng = np.random.default_rng(seed)
    out = np.zeros((h, w), np.float32)
    amp, total, g = 1.0, 0.0, base_grid
    for _ in range(octaves):
        gw = max(2, int(g * aspect))
        gh = max(2, int(g))
        grid = (rng.random((gh, gw)).astype(np.float32) * 2 - 1)
        up = np.asarray(Image.fromarray(grid, 'F').resize((w, h), Image.BICUBIC), dtype=np.float32)
        out += up * amp
        total += amp
        amp *= 0.5
        g *= 2
    return out / max(total, 1e-6)


def fractal_warp(img, amplitude, seed=1, octaves=5):
    """沿经纬度做分形位移：海岸线因此长出真实的海湾/岬角/半岛，
    而不是多边形那种几十公里一段的折线。经度方向环绕，纬度夹紧。"""
    w, h = img.size
    arr = np.asarray(img, dtype=np.float32)
    dx = fbm_field(w, h, octaves, 6, seed) * amplitude
    dy = fbm_field(w, h, octaves, 6, seed + 977) * amplitude * 0.85
    xs = (np.arange(w, dtype=np.float32)[None, :] + dx) % w
    ys = np.clip(np.arange(h, dtype=np.float32)[:, None] + dy, 0, h - 1)
    x0 = np.floor(xs).astype(np.int32) % w
    y0 = np.floor(ys).astype(np.int32)
    x1 = (x0 + 1) % w
    y1 = np.minimum(y0 + 1, h - 1)
    fx = xs - np.floor(xs); fy = ys - np.floor(ys)
    out = (arr[y0, x0] * (1 - fx) * (1 - fy) + arr[y0, x1] * fx * (1 - fy)
           + arr[y1, x0] * (1 - fx) * fy + arr[y1, x1] * fx * fy)
    return Image.fromarray(np.clip(out, 0, 255).astype(np.uint8), 'L')


def gauss_blob(img, cx, cy, radius_px, strength):
    """在 img 上叠一个高斯斑（近似：画实心圆再模糊由调用者统一做）"""
    d = ImageDraw.Draw(img)
    r = radius_px
    d.ellipse([cx - r, cy - r, cx + r, cy + r], fill=int(255 * strength))

def coast_distance_km(land_img):
    """到最近陆地的距离（km），写进气候图 B 通道，用来生成大陆架水深（对话 33）。

    遮罩是二值的（海/陆），距离场才是「离岸多远」的唯一来源——
    没有它，地形函数只能按遮罩值推距离，而遮罩值只在海岸那一个像素内有效，
    结果是离岸 5 km 就掉到 5000 m 深，根本没有大陆架。
    chamfer 3-4 两遍扫描；行内那一步用「减下标 → 前缀最小 → 加下标」向量化。
    """
    a = np.asarray(land_img.resize((CW, CH), Image.LANCZOS), dtype=np.float32) / 255.0
    is_land = a > 0.5
    INF = 1e6
    d = np.where(is_land, 0.0, INF).astype(np.float32)
    idx = np.arange(CW, dtype=np.float32)
    D = 1.41421356

    def relax_row(row, nb):
        r = np.minimum(row, nb + 1.0)
        r[1:] = np.minimum(r[1:], nb[:-1] + D)
        r[:-1] = np.minimum(r[:-1], nb[1:] + D)
        return r

    for y in range(CH):
        row = d[y]
        if y > 0:
            row = relax_row(row, d[y - 1])
        d[y] = np.minimum(row, np.minimum.accumulate(row - idx) + idx)
    for y in range(CH - 1, -1, -1):
        row = d[y]
        if y < CH - 1:
            row = relax_row(row, d[y + 1])
        # 反向：距离 = row[x'] + (x' - x)，所以是 min(row + idx) - idx
        # （写成 min(row - idx) + idx 会得到负值，clip 之后整张图一大半变 0）
        d[y] = np.minimum(row, np.minimum.accumulate((row + idx)[::-1])[::-1] - idx)

    lat = 90.0 - (np.arange(CH, dtype=np.float32) + 0.5) / CH * 180.0
    # 等距圆柱下东西向一格只有 cos(lat) 那么多公里；南北向恒定。
    # chamfer 是各向同性的，这里用 (0.5 + 0.5cos) 折中，别让高纬陆架宽一倍。
    cell_km = math.pi * 6371.0 / CH
    return d * cell_km * (0.5 + 0.5 * np.cos(np.deg2rad(lat)))[:, None]


def coast_dist_byte(land_img):
    """量化成 Uint8：2 km / 单位，255 → 510 km。"""
    km = coast_distance_km(land_img)
    return Image.fromarray(np.clip(km * 0.5, 0, 255).astype(np.uint8), 'L')


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    root = os.path.dirname(here)

    # ---------- 陆地遮罩 ----------
    land = Image.new('L', (TW, TH), 0)
    d = ImageDraw.Draw(land)
    draw_polys(d, [AFRICA, EURASIA, N_AMERICA, S_AMERICA, AUSTRALIA, ANTARCTICA, GREENLAND], TW, TH, 255)
    draw_polys(d, ISLANDS, TW, TH, 255)
    draw_polys(d, SEAS, TW, TH, 0)
    # 分形位移：幅度 ≈ 7 像素 ≈ 0.6° ≈ 68 km，五层倍频——
    # 这一级正好是「半岛 / 海湾」的尺度，也是多边形最假的地方
    land = fractal_warp(land, amplitude=7.0 * SC, seed=31, octaves=6)
    # 模糊出软边：0.5 等值线仍然落在（位移后的）边界上
    land.smooth = land.filter(ImageFilter.GaussianBlur(2.6 * SC))
    # 拉伸对比：离岸 1.5° 外就饱和到 0/255，同时保留海岸线处的梯度
    lut = []
    for i in range(256):
        v = (i / 255.0 - 0.5) * 3.2 + 0.5
        lut.append(int(max(0, min(1, v)) * 255))
    landS = land.smooth.point(lut)

    # ---- 对话 91：真实群岛小岛 ----
    # 必须在上面的 GaussianBlur(13.9 px ≈ 133 km) 之后再叠：几公里宽的小岛
    # 先画再模糊会被彻底抹平（中心值掉到 <1）。这里单独画一张、只做 1 px 柔边，
    # 再用 max 合成，小岛才有清晰可辨的轮廓和自己的浅滩过渡带。
    isle = Image.new('L', (TW, TH), 0)
    di2 = ImageDraw.Draw(isle)
    for lon, lat, rx, ry, rot in GEO.iter_islets():
        cx, cy = xy(lon, lat, TW, TH)
        px = max(1.0, rx / 360.0 * TW)
        py = max(1.0, ry / 180.0 * TH)
        a = math.radians(rot)
        ca, sa = math.cos(a), math.sin(a)
        pts = []
        for k in range(28):
            t = k / 28.0 * math.tau
            ux, uy = math.cos(t) * px, math.sin(t) * py
            pts.append((cx + ux * ca - uy * sa, cy + ux * sa + uy * ca))
        di2.polygon(pts, fill=238)
    isle = isle.filter(ImageFilter.GaussianBlur(1.0))
    landS = Image.fromarray(
        np.maximum(np.asarray(landS, dtype=np.uint8), np.asarray(isle, dtype=np.uint8)), 'L')

    # ---------- 山脉 ----------
    mtn = Image.new('L', (TW, TH), 0)
    dm = ImageDraw.Draw(mtn)
    for pts, halfw, amp in RANGES:
        px = [xy(lon, lat, TW, TH) for lon, lat in pts]
        width = max(3, int(halfw / 180.0 * TH * 2))
        dm.line(px, fill=int(255 * amp), width=width, joint='curve')
        for p in px:
            r = width * 0.5
            dm.ellipse([p[0] - r, p[1] - r, p[0] + r, p[1] + r], fill=int(255 * amp))
    for poly, amp in PLATEAUS:
        draw_polys(dm, [poly], TW, TH, int(255 * amp))
    mtn = mtn.filter(ImageFilter.GaussianBlur(2.0 * SC))
    # 山脉只保留在陆地上
    mtn = Image.composite(mtn, Image.new('L', (TW, TH), 0), landS.point(lambda v: 255 if v > 120 else 0))
    # 用噪声调制强度：真实山系是「一串山脉 + 垭口」，不是一条等宽的色带
    ma = np.asarray(mtn, dtype=np.float32) / 255.0
    mod = 0.58 + 0.62 * np.clip(fbm_field(TW, TH, 5, 90, 77) * 0.5 + 0.5, 0, 1)
    ma = np.clip(ma * mod, 0, 1)
    mtn = Image.fromarray((ma * 255).astype(np.uint8), 'L')
    mtn = mtn.filter(ImageFilter.GaussianBlur(1.0 * SC))

    # ---------- 气候图 ----------
    arid = Image.new('L', (CW, CH), 78)      # 基准 0.31
    da = ImageDraw.Draw(arid)
    for box, s in [(b[:4], b[4]) for b in WET_BOXES]:
        lon0, lat0, lon1, lat1 = box
        x0, y0 = xy(lon0, lat0, CW, CH)
        x1, y1 = xy(lon1, lat1, CW, CH)
        da.rectangle([min(x0, x1), min(y0, y1), max(x0, x1), max(y0, y1)], fill=int(255 * (0.16 * s)))
    for lon0, lat0, lon1, lat1, s in ARID_BOXES:
        x0, y0 = xy(lon0, lat0, CW, CH)
        x1, y1 = xy(lon1, lat1, CW, CH)
        da.rectangle([min(x0, x1), min(y0, y1), max(x0, x1), max(y0, y1)], fill=int(255 * s))
    arid = arid.filter(ImageFilter.GaussianBlur(5.0 * (CH / 192.0)))

    ice = Image.new('L', (CW, CH), 0)
    di = ImageDraw.Draw(ice)
    # 南极
    di.rectangle([0, xy(0, -66, CW, CH)[1], CW, CH], fill=255)
    # 格陵兰
    draw_polys(di, [GREENLAND], CW, CH, 235)
    ice = ice.filter(ImageFilter.GaussianBlur(3.0 * (CH / 192.0)))
    # 对话 91：真实山地冰川带。气候图只有 1024×512，山地雪带（几度宽）
    # 在 8 px 大模糊之前画会被抹平；这里单独画、只做 1.2 px 柔边再 max 合成。
    # 让阿尔卑斯 / 阿拉斯加 / 巴塔哥尼亚 / 喜马拉雅在太空视角也有连贯雪脊。
    gl = Image.new('L', (CW, CH), 0)
    dg = ImageDraw.Draw(gl)
    for lon, lat, rx, ry, s in GEO.GLACIERS:
        cx, cy = xy(lon, lat, CW, CH)
        px = max(1.4, rx / 360.0 * CW)
        py = max(1.2, ry / 180.0 * CH)
        dg.ellipse([cx - px, cy - py, cx + px, cy + py], fill=int(255 * s))
    gl = gl.filter(ImageFilter.GaussianBlur(1.2))
    ice = Image.fromarray(
        np.maximum(np.asarray(ice, dtype=np.uint8), np.asarray(gl, dtype=np.uint8)), 'L')
    ice = Image.composite(ice, Image.new('L', (CW, CH), 0), landS.resize((CW, CH), Image.LANCZOS).point(lambda v: 255 if v > 110 else 0))

    climate = Image.merge('RGB', (arid, ice, coast_dist_byte(landS)))
    climate.save(os.path.join(root, 'earth-climate.png'), optimize=True)

    # ---------- 城市 ----------
    # 真实夜间灯光图不是一个城市一个点，而是「城市群 + 卫星城 + 沿海带」连成的网。
    # 只撒 120 个大都市，从 2000 km 看就是十几个孤岛；这里补三层。
    land_np = np.asarray(landS, dtype=np.float32) / 255.0
    arid_np = np.asarray(arid.resize((TW, TH), Image.LANCZOS), dtype=np.float32) / 255.0
    ice_np = np.asarray(ice.resize((TW, TH), Image.LANCZOS), dtype=np.float32) / 255.0
    city = np.zeros((TH, TW), dtype=np.float32)

    def blob(cx, cy, r, s_):
        r = max(0.9 * SC, r)
        x0, x1 = int(max(0, cx - r * 2.6)), int(min(TW - 1, cx + r * 2.6))
        y0, y1 = int(max(0, cy - r * 2.6)), int(min(TH - 1, cy + r * 2.6))
        if x1 <= x0 or y1 <= y0:
            return
        xs = np.arange(x0, x1 + 1) - cx
        ys = np.arange(y0, y1 + 1) - cy
        d2 = (ys[:, None] ** 2 + xs[None, :] ** 2) / (r * r)
        city[y0:y1 + 1, x0:x1 + 1] += (np.exp(-d2 * 1.9) * s_).astype(np.float32)

    for lon, lat, st, rad in CITIES:
        cx, cy = xy(lon, lat, TW, TH)
        r = max(1.3, rad / 180.0 * TH)
        blob(cx, cy, r * 0.30, st)
        blob(cx, cy, r * 0.80, st * 0.30)
        # 卫星城：城市周边 2.6 倍半径内撒一圈小镇
        rng = np.random.default_rng(int(abs(lon * 97 + lat * 131)) + 7)
        n = int(5 + 22 * st)
        for _ in range(n):
            a = rng.random() * 2 * math.pi
            rr = (rng.random() ** 1.5) * r * 2.6
            px = cx + math.cos(a) * rr * 1.0
            py = cy + math.sin(a) * rr * 1.0
            blob(px, py, 3.2, (st * 0.55 * (1.0 - rr / (r * 2.6)) + 0.10) * 0.80)

    # 沿海灯光带：真实人口高度集中在海岸线 50 km 内
    gx = np.abs(np.diff(land_np, axis=1, prepend=land_np[:, :1]))
    gy = np.abs(np.diff(land_np, axis=0, prepend=land_np[:1, :]))
    coast = np.clip((gx + gy) * 3.2 / SC, 0, 1) * (land_np > 0.55)
    lat_grid = np.abs(90.0 - (np.arange(TH, dtype=np.float32)[:, None] + 0.5) / TH * 180.0)
    polar = np.clip(1.0 - (lat_grid - 50.0) / 16.0, 0.0, 1.0)   # 50° 起淡出，66° 归零
    city += coast * 0.16 * (1.0 - ice_np) * (1.0 - arid_np * 0.55) * polar

    # 随机小城镇：按陆地/非沙漠/非冰盖过滤，撒出真实的「星点」底噪
    rng = np.random.default_rng(20261107)
    cand = int(90000 * SC * SC)          # 按面积放大，保持「每平方公里城镇数」不变
    ys = rng.integers(0, TH, cand)
    xs = rng.integers(0, TW, cand)
    latg = np.abs(90.0 - (ys + 0.5) / TH * 180.0)   # y=0 是北极 → 90°
    latw = np.clip(1.0 - (latg - 32.0) / 22.0, 0.0, 1.0) ** 1.4   # 32° 起衰减，54° 之后几乎没有
    dense = (land_np[ys, xs] > 0.62) & (ice_np[ys, xs] < 0.20)
    w = latw * (1.0 - arid_np[ys, xs]) ** 1.6
    keep = rng.random(cand) < np.clip(w * 0.16, 0.0, 0.85)
    sel = dense & keep
    yy, xx = ys[sel], xs[sel]
    vals = 0.10 + rng.random(len(yy)).astype(np.float32) * 0.26
    np.add.at(city, (yy, xx), vals)

    city = np.clip(city, 0, 1.0)
    city_img = Image.fromarray((np.clip(city, 0, 1) ** 0.85 * 255).astype(np.uint8), 'L').filter(ImageFilter.GaussianBlur(1.4))
    city = city_img

    # ---------- 合成地形图（RGB）----------
    terr = Image.merge('RGB', (landS, mtn, city))
    terr.save(os.path.join(root, 'earth-terrain.png'), optimize=True)

    # 对话 91：build.mjs 从 public/data/ 读，脚本原本只写项目根目录，
    # 靠人工同步。这里自动同步，避免「重跑了脚本但页面还是旧地球」。
    import shutil
    for f in ('earth-terrain.png', 'earth-climate.png'):
        shutil.copy2(os.path.join(root, f), os.path.join(root, 'public', 'data', f))
        p = os.path.join(root, f)
        print(f, os.path.getsize(p), 'bytes', '-> public/data/')

